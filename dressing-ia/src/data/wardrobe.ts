import type { Garment, Preferences } from '@/domain/types';
import { COLOR_PRESETS_BY_NAME, type ColorName } from '@/data/taxonomy';

type GarmentColor = Pick<Garment, 'hue' | 'saturation' | 'lightness' | 'colorName'>;

/** Reprend les valeurs HSL de la palette : aucune teinte n'est saisie deux fois. */
function couleur(name: ColorName): GarmentColor {
  const preset = COLOR_PRESETS_BY_NAME[name];
  return {
    hue: preset.hue,
    saturation: preset.saturation,
    lightness: preset.lightness,
    colorName: preset.name,
  };
}

